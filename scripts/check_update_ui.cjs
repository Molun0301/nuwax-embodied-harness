/* Run with jsdom available: NODE_PATH=/path/to/node_modules node scripts/check_update_ui.cjs */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'gateways/http/static/console.html'), 'utf8'), {url: 'http://localhost:8766/console', runScripts: 'outside-only', pretendToBeVisual: true});
const w = dom.window;
const $ = id => w.document.getElementById(id);
let timer;
let posts = [];
let fail = false;
let latest = {available: true, running_revision: 'a'.repeat(40), latest_revision: 'b'.repeat(40), checked_at: Date.now()/1000, install_available: true, settings: {auto_check: true, auto_install: false, interval_minutes: 60}, transaction: {state: 'idle'}};
w.AbortSignal.timeout = () => undefined;
w.setInterval = fn => {timer = fn;};
w.HTMLElement.prototype.scrollIntoView = () => {};
w.HTMLDialogElement.prototype.showModal = function () {this.open = true;};
w.HTMLDialogElement.prototype.close = function () {this.open = false;};
$('viewSwitchConfig').addEventListener('click', () => $('config-view').classList.add('active'));
w.fetch = async (url, opts) => {
  if (opts.method === 'POST') posts.push({url, body: JSON.parse(opts.body)});
  if (fail) throw new Error('offline');
  if (url.endsWith('/install')) latest = {...latest, transaction: {state: 'queued', message: '已受理'}};
  return {ok: true, json: async () => JSON.parse(JSON.stringify(latest))};
};
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  w.eval(fs.readFileSync(path.join(root, 'gateways/http/static/js/console-updates.js'), 'utf8'));
  await tick();
  assert.equal($('updateNewBadge').hidden, false);
  assert.equal($('updateInstall').disabled, false);
  $('updateNewBadge').click();
  assert($('config-view').classList.contains('active'));
  $('updateInstall').click();
  assert.equal($('updateDialog').open, true);
  $('updateCancel').click();
  assert.equal($('updateDialog').open, false);
  assert.equal(posts.length, 0);
  $('updateAutoCheck').checked = false;
  $('updateAutoCheck').dispatchEvent(new w.Event('change'));
  timer();await tick();
  assert.equal($('updateAutoCheck').checked, false, 'poll must preserve unsaved settings');
  $('updateInterval').value = 1;
  $('updateSave').click();await tick();
  assert.equal(posts.length, 0, 'invalid interval must not be sent');
  $('updateInterval').value = 60;
  $('updateCheck').click();$('updateCheck').click();await tick();
  assert.equal(posts.filter(x => x.url.endsWith('/check')).length, 1, 'double click must coalesce');
  $('updateInstall').click();$('updateConfirm').click();await tick();
  assert.equal(posts.at(-1).body.revision, 'b'.repeat(40));
  assert.equal($('updateInstall').disabled, true);
  fail = true;timer();await tick();
  assert($('updateMessage').textContent.includes('等待重连'));
  fail = false;
  latest = {...latest, available: false, running_revision: 'b'.repeat(40), transaction: {state: 'succeeded', message: '更新完成'}};
  timer();await tick();
  assert.equal($('updateNewBadge').hidden, true);
  assert.equal($('updateMessage').textContent, '更新完成');
  latest = {...latest, available: true, transaction: {state: 'rolled_back', message: '已恢复原版本'}};
  timer();await tick();
  assert.equal($('updateMessage').textContent, '已恢复原版本');
  latest = {...latest, install_available: false, install_unavailable_reason: '旧部署需原入口'};
  timer();await tick();
  assert.equal($('updateInstall').disabled, true);
  assert.equal($('updateUnavailable').textContent, '旧部署需原入口');
  latest = {...latest, install_available: true, transaction: {state: 'recovery_required', message: '需要人工恢复'}};
  timer();await tick();
  assert.equal($('updateInstall').disabled, true);
  assert.equal($('updateCheck').disabled, false);
  assert.equal($('updateMessage').textContent, '需要人工恢复');
  console.log('Update UI: DOM/interaction assertions passed');
  dom.window.close();
})().catch(error => {console.error(error); dom.window.close(); process.exitCode=1;});
