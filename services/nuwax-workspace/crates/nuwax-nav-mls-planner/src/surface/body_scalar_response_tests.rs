fn frozen(distance: f64) -> (Vec<([f64; 3], f64, f64)>, [f64; 3]) {
    let base = [
        -1.9531105903889756,
        0.07474406681550412,
        -0.4443271200058306,
    ];
    let direction = [-0.9450256091422736, -0.3269963274928532];
    let radius = 0.39003151182921547_f64;
    let origin = [
        base[0] + distance * direction[0],
        base[1] + distance * direction[1],
        base[2],
    ];

    let rows = FROZEN_POINTS
        .iter()
        .copied()
        .filter_map(|(p, l)| {
            let w = (1.0
                - ((p[0] - origin[0]).powi(2) + (p[1] - origin[1]).powi(2)) / radius.powi(2))
            .max(0.0)
            .powi(2);
            (w > 0.0).then_some((p, l, w))
        })
        .collect();
    (rows, origin)
}
fn analytic_map(slope: f64, patch: bool) -> SurfaceSnapshot {
    let d = f64::from(0.05_f32);
    let model = SurfaceBodyEnvelope {
        footprint_xy_m: vec![[-0.3, -0.15], [0.3, -0.15], [0.3, 0.15], [-0.3, 0.15]],
        z_bounds_m: [if patch { -0.4 } else { -0.448 }, 0.057],
        body_to_support_z_m: SUPPORT,
        max_step_up_m: 0.15,
        max_step_down_m: 0.15,
        max_cross_slope_deg: 20.0,
        support_uncertainty_m: 0.0,
    };
    let mut keys = Vec::<[i32; 3]>::new();
    for x in -24..24 {
        for y in -24..24 {
            let (low_top, high_top) = if patch {
                if [x, y] == [7, 2] {
                    (-2, -1)
                } else {
                    (-1, 0)
                }
            } else {
                let analytic = slope * (f64::from(x) + 0.5) * d;
                ((analytic / d).floor() as i32, (analytic / d).ceil() as i32)
            };
            for z in low_top - 1..high_top {
                keys.push([x, y, z]);
            }
        }
    }
    let points: Vec<_> = keys
        .iter()
        .map(|k| {
            (
                (f64::from(k[0]) + 0.5) * d,
                (f64::from(k[1]) + 0.5) * d,
                (f64::from(k[2]) + 0.5) * d,
            )
        })
        .map(|(x, y, z)| (x as f32, y as f32, z as f32))
        .collect();
    let mut blocks = BTreeMap::<[i32; 3], BTreeMap<[i32; 3], SurfaceObservation>>::new();
    for key in keys {
        blocks
            .entry(key.map(|v| v.div_euclid(32)))
            .or_default()
            .insert(
                key,
                SurfaceObservation {
                    observed_ns: 0,
                    hits: 0,
                },
            );
    }
    let mut observations = SurfaceObservations::new(0.05, 32).unwrap();
    for (key, values) in blocks {
        observations.replace_block(key, values).unwrap();
    }
    observations.mark_complete_geometry_source();
    let cfg = Config {
        voxel_size: 0.1,
        robot_height: 0.1,
        surface_closing_radius: 0.0,
        wall_clearance_m: 0.0,
        step_threshold_m: 0.21,
        min_step_tread_depth_m: 0.2,
        world_frame: "map".into(),
        node_spacing_m: 0.3,
        wall_buffer_m: 0.0,
        wall_buffer_weight: 0.0,
        max_slope_deg: 25.0,
        step_penalty_weight: 1.0,
        goal_tolerance: 0.1,
        viz_publish_hz: 0.0,
    };
    SurfaceSnapshot::from_points(&points, cfg, 0.05)
        .unwrap()
        .with_body_envelope(model)
        .unwrap()
        .with_observations(Some(Arc::new(observations)))
        .with_ground_evidence(GroundEvidence::MeasuredSurface)
}
const SUPPORT: f64 = 0.4;
fn analytic_truth(x: f64, slope: f64) -> Pose {
    let gap = if slope == 0.0 { 0.01 } else { 0.06 };
    let angle = slope.atan();
    (
        [
            x,
            0.0,
            slope * x + (SUPPORT + gap) * (1.0 + slope * slope).sqrt(),
        ],
        [0.0, -(angle * 0.5).sin(), 0.0, (angle * 0.5).cos()],
    )
}
fn analytic_errors(p: Pose, t: Pose) -> [f64; 2] {
    let n = rotation(p.1).unwrap()[2];
    let expected = rotation(t.1).unwrap()[2];
    let c = cross(n, expected);
    [p.0[2] - t.0[2], dot(c, c).sqrt().atan2(dot(n, expected))]
}
fn analytic_prism_clearance(map: &SurfaceSnapshot, p: Pose, slope: f64) -> f64 {
    let n = normalize([-slope, 0.0, 1.0]);
    let r = rotation(p.1).unwrap();
    let model = map.body_envelope().unwrap();
    model
        .footprint_xy_m
        .iter()
        .flat_map(|xy| {
            model
                .z_bounds_m
                .map(|z| dot(n, world(r, p.0, [xy[0], xy[1], z])))
        })
        .fold(f64::INFINITY, f64::min)
}

#[test]
fn external_low_patch_does_not_pull_body_into_an_independent_flat_plane() {
    // Truth is z=0 under the full swept prism/support region, body z=.41,
    // normal Z, bottom z=.01. Observed [-d,0] is a quantization band, not
    // a second true ground at -d. The patch has true top -d and band [-2d,-d].
    let map = analytic_map(0.0, true);
    let d = f64::from(0.05_f32);
    let radius = map.body_envelope().unwrap().radius() + d;
    let crossing = 7.5 * d - (radius * radius - (2.5 * d).powi(2)).sqrt();
    let forward: Vec<_> = (0..=4)
        .map(|i| crossing - 0.002 + f64::from(i) * 0.001)
        .collect();
    let mut path = forward.clone();
    path.extend(forward[..4].iter().rev().copied());
    let minimum_patch_gap = 7.0 * d - (forward[4] + 0.3);
    assert!(
        minimum_patch_gap > 0.0,
        "whole swept body and support projection must stay outside patch"
    );
    let mut actual = analytic_truth(path[0], 0.0);
    let mut max_error = 0.0_f64;
    for pair in path.windows(2) {
        let a = analytic_truth(pair[0], 0.0);
        let t = analytic_truth(pair[1], 0.0);
        map.validate_body_motion(a, t, &[])
            .expect("independent truth path must be admissible");
        let frozen = map.body_pose_after_motion(a, [t.0[0], 0.0], 0.0).unwrap();
        assert_flat_response_matches_reference(&map, a, frozen);
        assert!(
            analytic_prism_clearance(&map, frozen, 0.0) >= 0.0,
            "fitted response must not enter the declared true plane"
        );
        let next = map
            .body_pose_after_motion(actual, [t.0[0], 0.0], 0.0)
            .unwrap();
        assert_flat_response_matches_reference(&map, actual, next);
        assert!(analytic_prism_clearance(&map, next, 0.0) >= 0.0);
        let errors = analytic_errors(next, t);
        assert_eq!(errors[1], 0.0);
        max_error = max_error.max(errors[0].abs());
        actual = next;
    }
    eprintln!("INTEGRATED_ANALYTIC_FLAT segments=8 max_height_error_m={max_error:?} return_error_m={:?} minimum_patch_gap_m={minimum_patch_gap:?}",actual.0[2]-analytic_truth(path[0],0.0).0[2]);
}

#[test]
fn independent_quantized_ramp_retains_legacy_noncommon_response() {
    // Prescribed plane z=.2x and constant plane-normal orientation. Body normal
    // distance .46m gives .012m prism clearance. Truth is not a voxel band edge.
    let slope = 0.2;
    let map = analytic_map(slope, false);
    let forward: Vec<_> = (0..=20).map(|i| -0.1 + f64::from(i) * 0.01).collect();
    let mut path = forward.clone();
    path.extend(forward[..20].iter().rev().copied());
    let radius = map.body_envelope().unwrap().radius() + f64::from(0.05_f32);
    let mut actual = analytic_truth(path[0], slope);
    let mut maxima = [0.0_f64; 2];
    for pair in path.windows(2) {
        let a = analytic_truth(pair[0], slope);
        let t = analytic_truth(pair[1], slope);
        map.validate_body_motion(a, t, &[])
            .expect("analytic ramp truth must be admissible");
        let frozen = map.body_pose_after_motion(a, [t.0[0], 0.0], 0.0).unwrap();
        map.validate_body_motion(a, frozen, &[]).unwrap();
        let r = rotation(actual.1).unwrap();
        let origin = [actual.0[0], actual.0[1], actual.0[2] - SUPPORT / r[2][2]];
        let rows = map.fine_contact_domain(origin, radius).unwrap();
        let low = rows.iter().map(|p| p.1).fold(f64::NEG_INFINITY, f64::max);
        let high = rows.iter().map(|p| p.0[2]).fold(f64::INFINITY, f64::min);
        assert!(
            low > high,
            "fixture must exercise the unchanged noncommon solver"
        );
        assert_eq!(
            fit_contact_plane(&rows, origin),
            original_fit_contact_plane(&rows, origin)
        );
        let next = map
            .body_pose_after_motion(actual, [t.0[0], 0.0], 0.0)
            .unwrap();
        map.validate_body_motion(actual, next, &[]).unwrap();
        assert!(analytic_prism_clearance(&map, next, slope) >= 0.0);
        let errors = analytic_errors(next, t);
        for i in 0..2 {
            maxima[i] = maxima[i].max(errors[i].abs());
        }
        actual = next;
    }
    // Quantized ramp errors are explicitly retained, not relabeled exact truth.
    eprintln!("INTEGRATED_ANALYTIC_RAMP segments=40 max_height_error_m={} max_normal_error_rad={} return_error={:?}",maxima[0],maxima[1],analytic_errors(actual,analytic_truth(path[0],slope)));
}

